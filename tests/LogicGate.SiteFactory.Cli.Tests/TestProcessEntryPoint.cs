using System.Diagnostics;
using System.Globalization;
using System.IO.Pipes;

namespace LogicGate.SiteFactory.Cli.Tests;

// Private test executable modes; normal discovery/execution still uses xUnit's entry point.
internal static class TestProcessEntryPoint
{
    internal const string FixtureMode = "--sitefactory-process-fixture";

    public static int Main(string[] args)
    {
        if (args.Length == 2 && args[0] == OwnedProcessRunner.SupervisorMode)
            return OwnedProcessRunner.SuperviseAsync(args[1]).GetAwaiter().GetResult();
        if (args.Length > 0 && args[0] == FixtureMode)
            return RunFixtureAsync(args).GetAwaiter().GetResult();
        return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);
    }

    private static async Task<int> RunFixtureAsync(string[] args)
    {
        if (args[1] == "output")
        {
            Console.OutputEncoding = System.Text.Encoding.UTF8;
            if (await Console.In.ReadLineAsync() is not null)
                return 99;
            await Console.Out.WriteAsync("été\n" + Environment.GetEnvironmentVariable("SF_TEST_PROCESS_VALUE") + "\n");
            await Console.Error.WriteAsync("error\n");
            return 23;
        }
        using NamedPipeClientStream control = new(".", args[2], PipeDirection.InOut, PipeOptions.Asynchronous);
        await control.ConnectAsync(10000);
        using StreamReader reader = new(control, leaveOpen: true);
        using StreamWriter writer = new(control, leaveOpen: true) { AutoFlush = true };
        using FileStream? heldFile = args[1] == "child"
            ? new(args[3], FileMode.CreateNew, FileAccess.Write, FileShare.None) : null;
        await writer.WriteLineAsync(Environment.ProcessId.ToString(CultureInfo.InvariantCulture));
        if (args[1] == "parent")
        {
            ProcessStartInfo child = new("dotnet") { UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true };
            foreach (string argument in new[] { typeof(TestProcessEntryPoint).Assembly.Location, FixtureMode, "child", args[3], args[4] })
                child.ArgumentList.Add(argument);
            using Process process = Process.Start(child) ?? throw new InvalidOperationException("Fixture child did not start.");
            await reader.ReadLineAsync();
            return 23;
        }
        await reader.ReadLineAsync();
        return 0;
    }
}
